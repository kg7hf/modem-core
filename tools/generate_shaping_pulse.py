"""Generate modem/m110a/body_shaping_pulse.hpp: the 110A transmitter's root-raised-cosine
pulse as float constants.

The pulse was designed at start-up from the platform's sin/cos/sqrt, which round
differently from one math library to another, so the transmitted audio differed in its
last bits between builds. Here each tap is the exact pulse value, computed in double
precision with the same three cases as make_root_raised_cosine_taps
(modem/common/dsp/timing_recovery.cpp), normalized to unit energy in double and rounded
once to float. The header holds the result as hexadecimal float literals, so every
compiler reads the same bits.

usage: python tools/generate_shaping_pulse.py modem/m110a/body_shaping_pulse.hpp
"""
import math
import struct
import sys

SAMPLES_PER_SYMBOL = 20   # body_audio_samples_per_symbol: 48 kHz at 2400 baud
SPAN_SYMBOLS = 16         # body_audio_shaping_span_symbols
ROLLOFF = 0.25            # the transmitter's shaping rolloff
TAPS = 2 * SPAN_SYMBOLS * SAMPLES_PER_SYMBOL + 1
PER_LINE = 4


def to_float32(value: float) -> float:
    return struct.unpack("<f", struct.pack("<f", value))[0]


def pulse() -> list[float]:
    center = (TAPS - 1) / 2.0
    taps = []
    for index in range(TAPS):
        time = (index - center) / SAMPLES_PER_SYMBOL
        if abs(time) < 1.0e-6:
            value = 1.0 + ROLLOFF * (4.0 / math.pi - 1.0)
        elif abs(abs(4.0 * ROLLOFF * time) - 1.0) < 1.0e-5:
            angle = math.pi / (4.0 * ROLLOFF)
            value = (ROLLOFF / math.sqrt(2.0)) * ((1.0 + 2.0 / math.pi) * math.sin(angle) + (1.0 - 2.0 / math.pi) * math.cos(angle))
        else:
            numerator = math.sin(math.pi * time * (1.0 - ROLLOFF)) + 4.0 * ROLLOFF * time * math.cos(math.pi * time * (1.0 + ROLLOFF))
            denominator = math.pi * time * (1.0 - 16.0 * ROLLOFF * ROLLOFF * time * time)
            value = numerator / denominator
        taps.append(value)
    norm = math.sqrt(sum(value * value for value in taps))
    return [to_float32(value / norm) for value in taps]


def literal(value: float) -> str:
    if value == 0.0:
        return "0.0F"
    mantissa, exponent = value.hex().split("p")
    mantissa = mantissa.rstrip("0").rstrip(".")
    return f"{mantissa}p{exponent}F"


def header(taps: list[float]) -> list[str]:
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Copyright (C) 2026 Paul R. Decker (KG7HF)",
        "",
        "#pragma once",
        "",
        "// =============================================================================",
        "// body_shaping_pulse - the 110A transmitter's root-raised-cosine pulse",
        f"// (rolloff {ROLLOFF}, {SAMPLES_PER_SYMBOL} samples a symbol, {SPAN_SYMBOLS} symbols each side) as constants.",
        "// GENERATED by tools/generate_shaping_pulse.py; do not edit.",
        "// -----------------------------------------------------------------------------",
        "// Each tap is the exact pulse value, normalized to unit energy and rounded once to",
        "// float, so the transmitted audio is the same bits on every compiler and math library.",
        "// =============================================================================",
        "",
        '#include "modem/m110a/body_waveform.hpp"',
        "",
        "#include <array>",
        "",
        "namespace modem::m110a",
        "{",
        "",
        "// clang-format off: generated, four taps a line",
        "inline constexpr std::array<float, body_audio_shaping_taps> body_shaping_pulse{",
    ]
    for start in range(0, TAPS, PER_LINE):
        lines.append("    " + ", ".join(literal(value) for value in taps[start:start + PER_LINE]) + ",")
    lines += ["};", "// clang-format on", "", "} // namespace modem::m110a"]
    return lines


def main() -> None:
    taps = pulse()
    assert all(taps[i] == taps[TAPS - 1 - i] for i in range(TAPS)), "the pulse is symmetric"
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as output:
        for line in header(taps):
            output.write(line)
            output.write("\n")


if __name__ == "__main__":
    main()
